export function catalogEntryToRow(entry: RecipeCatalogEntry, id = "") {
  return {
    id,
    title: entry.title,
    description: entry.description,
    lead: entry.lead,
    photoUrl: entry.photoUrl,
    prepTime: entry.prepTime,
    cookTime: entry.cookTime,
    servings: entry.servings,
    tags: entry.tags,
    ingredientsList: entry.ingredients,
    steps: entry.steps,
    tips: entry.tips,
  };
}

export function getCatalogRecipesForMemory(): ReturnType<typeof catalogEntryToRow>[] {
  return RECIPES_CATALOG.map((entry, i) => catalogEntryToRow(entry, `r${i + 1}`));
}
